/**
 * RN-5.2-Q — 15 minutos **sin cambiar de etapa** es un fallo.
 *
 * Se mide contra la última etapa, no contra el inicio: un análisis de 20
 * minutos repartido en etapas de 6, 7 y 7 no está colgado (QA-20, tercera
 * fila).
 */
const STALL_TIMEOUT_MINUTES = 15;

const STALL_TIMEOUT_MS = STALL_TIMEOUT_MINUTES * 60 * 1000;

/**
 * Días entre un análisis y el siguiente, por usuario.
 *
 * La cuenta que lo fija, con precios medidos y no estimados: un análisis cuesta
 * ~$0.20 y la suscripción Pro son **$4.99 al mes**. A cinco análisis diarios
 * —lo que esta constante permitía— un solo usuario costaría $30 al mes, seis
 * veces lo que paga. El punto de equilibrio está en ~25 análisis mensuales, y
 * eso dedicando el 100% de la cuota al motor, sin servidores ni margen.
 *
 * A uno por semana son ~$0.87 al mes: el 17% de la suscripción. Y no se pierde
 * nada por el camino — los fundamentales de una empresa cambian cada trimestre,
 * no cada día.
 */
